import { chromium } from "@playwright/test";
const [url, out] = process.argv.slice(2);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1400, height: 1000 } });
await p.goto(url); await p.waitForTimeout(2500);
await p.locator("button[role=combobox]").first().click();
await p.getByRole("option", { name: /Streamable HTTP/i }).click();
await p.locator("input#sse-url-input, input[placeholder*='URL' i]").first().fill("http://localhost:8091/mcp/");
await p.getByRole("button", { name: /^Connect$/ }).click(); await p.waitForTimeout(3000);
await p.getByRole("tab", { name: /Tools/i }).click();
await p.getByRole("button", { name: /List Tools/i }).click(); await p.waitForTimeout(2000);
await p.getByText("search_evidence", { exact: true }).first().click(); await p.waitForTimeout(800);
await p.locator("#requirement, textarea").first().fill("spaCy NER clinical notes");
await p.getByRole("button", { name: /Run Tool/i }).click(); await p.waitForTimeout(6000);
const res = p.getByText(/Tool Result/).first();
await res.scrollIntoViewIfNeeded(); await p.mouse.wheel(0, 400); await p.waitForTimeout(800);
await res.evaluate((el) => el.scrollIntoView({ block: "start" }));
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/inspector_call_result.png` });
await b.close();
